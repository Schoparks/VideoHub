import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { launchHeadlessRenderer } from './headless-renderer.mjs';
import { installReliabilityFixture } from './renderer-reliability-fixture.mjs';
import { connectPad, pressPad } from './controller-fixture.mjs';

const output = '.tmp/renderer-setting-editing';
await mkdir(output, { recursive: true });
const report = [];
for (const viewport of [{ width: 1440, height: 950 }, { width: 1920, height: 1080 }]) {
  const install = new Function(`(${installReliabilityFixture})(); window.reliability.failNextBootstrap = false;`);
  const { page, errors, close } = await launchHeadlessRenderer(viewport, install);
  try {
    await page.getByRole('button', { name: '设置', exact: true }).waitFor();
    assert.equal(await page.locator('.global-search button').count(), 0);
    assert.equal(await page.locator('.global-search input').count(), 1);
    const search = page.getByRole('textbox', { name: '搜索视频', exact: true });
    await search.press('Enter');
    await page.locator('.screen-keyboard').waitFor();
    await page.keyboard.press('Escape');
    await page.getByRole('dialog').waitFor({ state: 'detached' });
    await page.getByRole('button', { name: '设置', exact: true }).click();
    await connectPad(page);
    const columns = page.getByRole('combobox', { name: '卡片大小', exact: true });
    await columns.focus();
    await pressPad(page, 15);
    assert.equal(await columns.inputValue(), '0');
    await pressPad(page, 0);
    assert.equal(await columns.getAttribute('data-setting-editing'), 'true');
    await pressPad(page, 15);
    assert.equal(await columns.inputValue(), '2');
    await pressPad(page, 1);
    assert.equal(await columns.getAttribute('data-setting-editing'), null);
    assert.equal(await page.getByRole('dialog').count(), 1);
    await pressPad(page, 14);
    assert.equal(await columns.inputValue(), '2');
    await columns.press('Enter');
    await columns.press('ArrowLeft');
    assert.equal(await columns.inputValue(), '0');
    await columns.press('Enter');
    await columns.hover();
    await page.mouse.wheel(0, 120);
    await page.waitForTimeout(100);
    assert.equal(await columns.inputValue(), '0');
    await page.getByRole('tab', { name: '手柄', exact: true }).click();
    const range = page.getByRole('slider', { name: '摇杆死区', exact: true });
    await range.scrollIntoViewIfNeeded();
    const before = await range.inputValue();
    const bounds = await range.boundingBox();
    await range.click({ position: { x: bounds.width - 4, y: bounds.height / 2 } });
    assert.equal(await range.inputValue(), before);
    assert.equal(await range.getAttribute('data-setting-editing'), 'true');
    await range.press('ArrowRight');
    assert.notEqual(await range.inputValue(), before);
    await range.press('Escape');
    const committed = await range.inputValue();
    await page.mouse.move(bounds.x + 4, bounds.y + bounds.height / 2);
    await page.mouse.down();
    await page.mouse.move(bounds.x + bounds.width - 4, bounds.y + bounds.height / 2 + 35, { steps: 6 });
    await page.mouse.up();
    assert.equal(await range.inputValue(), committed);
    assert.equal(await range.getAttribute('data-setting-editing'), null);
    await page.screenshot({ path: `${output}/${viewport.width}.png` });
    assert.deepEqual(errors, []);
    report.push({ viewport, passed: true, checks: ['single search stop', 'empty Enter opens keyboard', 'confirm before select/range edit', 'back ends edit', 'wheel scroll does not edit', 'first slider tap and swipe do not change value'] });
  } finally { await close(); }
}
await writeFile(`${output}/report.json`, JSON.stringify(report, null, 2));
console.log(JSON.stringify(report, null, 2));
